const slug = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

export const BARCELONA_PLACES: SunPlace[] = ROWS.map(([name, type, lat, lng, barrio, r, tip]) => ({
  id: `bcn:${slug(name)}`,
  name,
  type,
  latitude: lat,
  longitude: lng,
  areaM2: Math.round(Math.PI * r * r),
  source: "curated",
  metadata: { barrio, radiusM: r, ...(tip ? { tip } : {}), ...(type === "terrace" ? { locationApproximate: true } : {}) },
}));
